import type { DnsHookConfig } from "../types";

const GENERATED_HEADER = "# Generated by Hydra; hydra update rewrites this file.";

export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

export function renderDisabledHook(): string {
  return `#!/usr/bin/env bash
${GENERATED_HEADER}
# Disabled in the Hydra profile; kept so runners started before the change still find it.
exit 0
`;
}

export function renderDnsHook(config: DnsHookConfig): string {
  return `#!/usr/bin/env bash
${GENERATED_HEADER}
# Waits until every host resolves, then lets the job start; fails the job on timeout.
set +e

hosts=(${config.hosts.map(shellQuote).join(" ")})
timeout_seconds=${config.timeoutSeconds}

if command -v dscacheutil >/dev/null 2>&1; then
  resolves() { dscacheutil -q host -a name "$1" 2>/dev/null | grep -q -e '^ip_address:' -e '^ipv6_address:'; }
elif command -v getent >/dev/null 2>&1; then
  resolves() { getent hosts "$1" >/dev/null 2>&1; }
else
  echo "::warning::Hydra skipped the DNS check: neither dscacheutil nor getent is available"
  exit 0
fi

pending=("\${hosts[@]}")
started=$SECONDS
waited=false
while :; do
  unresolved=()
  for host in "\${pending[@]}"; do
    resolves "$host" || unresolved+=("$host")
  done
  elapsed=$((SECONDS - started))
  if [ "\${#unresolved[@]}" -eq 0 ]; then
    if [ "$waited" = true ]; then
      echo "::warning::DNS recovered after $elapsed s"
    fi
    exit 0
  fi
  if [ "$elapsed" -ge "$timeout_seconds" ]; then
    echo "::error::DNS did not recover within $timeout_seconds s; unresolved: \${unresolved[*]}"
    exit 1
  fi
  if [ "$waited" = false ]; then
    echo "Waiting up to $timeout_seconds s for DNS: \${unresolved[*]}"
  fi
  waited=true
  pending=("\${unresolved[@]}")
  sleep 1
done
`;
}
