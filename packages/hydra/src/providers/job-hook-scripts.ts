import { isAbsolute } from "node:path";
import type { DnsHookConfig, WorkspaceCleanupHookConfig } from "../types";

const GENERATED_HEADER = "# Generated by Hydra; hydra update rewrites this file.";

export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

export function renderDisabledHook(): string {
  return `#!/usr/bin/env bash
${GENERATED_HEADER}
# Disabled in the Hydra profile; kept so runners started before the change still find it.
exit 0
`;
}

export function renderDnsHook(config: DnsHookConfig): string {
  return `#!/usr/bin/env bash
${GENERATED_HEADER}
# Waits until every host resolves, then lets the job start; fails the job on timeout.
set +e

hosts=(${config.hosts.map(shellQuote).join(" ")})
timeout_seconds=${config.timeoutSeconds}

if command -v dscacheutil >/dev/null 2>&1; then
  resolves() { dscacheutil -q host -a name "$1" 2>/dev/null | grep -q -e '^ip_address:' -e '^ipv6_address:'; }
elif command -v getent >/dev/null 2>&1; then
  resolves() { getent hosts "$1" >/dev/null 2>&1; }
else
  echo "::warning::Hydra skipped the DNS check: neither dscacheutil nor getent is available"
  exit 0
fi

pending=("\${hosts[@]}")
started=$SECONDS
waited=false
while :; do
  unresolved=()
  for host in "\${pending[@]}"; do
    resolves "$host" || unresolved+=("$host")
  done
  elapsed=$((SECONDS - started))
  if [ "\${#unresolved[@]}" -eq 0 ]; then
    if [ "$waited" = true ]; then
      echo "::warning::DNS recovered after $elapsed s"
    fi
    exit 0
  fi
  if [ "$elapsed" -ge "$timeout_seconds" ]; then
    echo "::error::DNS did not recover within $timeout_seconds s; unresolved: \${unresolved[*]}"
    exit 1
  fi
  if [ "$waited" = false ]; then
    echo "Waiting up to $timeout_seconds s for DNS: \${unresolved[*]}"
  fi
  waited=true
  pending=("\${unresolved[@]}")
  sleep 1
done
`;
}

export function renderCleanupHook(runnerRoot: string, config: WorkspaceCleanupHookConfig): string {
  if (!isAbsolute(runnerRoot) || runnerRoot === "/") {
    throw new Error(`Refusing to generate a workspace cleanup hook for runner directory "${runnerRoot}"`);
  }

  return `#!/usr/bin/env bash
${GENERATED_HEADER}
# Removes this job's workspace and temporary files from this runner's _work directory.
# Always exits 0 so a cleanup problem never fails a finished job; problems become warnings.
set +e
trap 'exit 0' EXIT
shopt -s dotglob nullglob

runner_root=${shellQuote(runnerRoot)}
keep_tool_cache=${config.keepToolCache}

note() { echo "Hydra cleanup: $*"; }
warn() { echo "::warning::Hydra cleanup: $*"; }

remove_entry() {
  local errors
  errors=$(rm -rf -- "$1" 2>&1 >/dev/null)
  if [ -e "$1" ] || [ -L "$1" ]; then
    warn "could not remove $1: \${errors%%$'\\n'*}"
    return 1
  fi
  return 0
}

clear_dir() {
  local dir=$1 entry name kept removed=0
  shift
  if [ -L "$dir" ]; then
    warn "refusing to clear $dir: it is a symbolic link"
    return
  fi
  [ -d "$dir" ] || return
  for entry in "$dir"/*; do
    name=\${entry##*/}
    for kept in "$@"; do
      [ "$name" = "$kept" ] && continue 2
    done
    remove_entry "$entry" && removed=$((removed + 1))
  done
  [ "$removed" -eq 0 ] || note "cleared $removed item(s) from $dir"
}

clean_job_workspace() {
  local candidate=$1 resolved relative top
  case "$candidate" in
    /*) ;;
    "")
      warn "the job workspace is not set; leaving it in place"
      return
      ;;
    *)
      warn "refusing to remove $candidate: it is not an absolute path"
      return
      ;;
  esac
  resolved=$(cd -P -- "$candidate" 2>/dev/null && pwd -P)
  if [ -z "$resolved" ]; then
    note "the job workspace $candidate is already gone"
    return
  fi
  case "$resolved" in
    "$work_root"/?*) ;;
    *)
      warn "refusing to remove $candidate: it resolves to $resolved, which is not inside $work_root"
      return
      ;;
  esac
  relative=\${resolved#"$work_root"/}
  top=\${relative%%/*}
  case "$top" in
    "" | _*)
      warn "refusing to remove $work_root/$top: it belongs to the runner"
      return
      ;;
  esac
  remove_entry "$work_root/$top" && note "removed $work_root/$top"
}

if [ -z "$runner_root" ] || [ "$runner_root" = / ]; then
  warn "the runner directory is not set; nothing cleaned"
  exit 0
fi
if [ -L "$runner_root/_work" ]; then
  warn "refusing to clean $runner_root/_work: it is a symbolic link"
  exit 0
fi
work_root=$(cd -P -- "$runner_root/_work" 2>/dev/null && pwd -P)
if [ -z "$work_root" ] || [ "$work_root" = / ]; then
  note "no _work directory to clean"
  exit 0
fi
cd -- "$work_root" || exit 0

clean_job_workspace "\${RUNNER_WORKSPACE:-\${GITHUB_WORKSPACE:-}}"
clear_dir "$work_root/_temp" _runner_file_commands _github_workflow
[ "$keep_tool_cache" = true ] || clear_dir "$work_root/_tool"
`;
}
